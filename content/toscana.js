<p>Sangiovese is not an easy grape. It ripens late, buds early, has thin skins that rot in a wet September, and gives generously if you let it, which is why so much Tuscan wine was thin and sour in the 1970s. It is also one of the most transparent grapes in the world: it shows exactly where it was grown and how carefully. On a cool clay hillside at 500 metres it makes a pale, nervous, herbal wine; on the warm limestone slopes south of Montalcino it makes something dark, dense and long-lived. Same grape, different face.</p>
